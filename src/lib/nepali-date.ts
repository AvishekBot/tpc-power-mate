const BS_MONTHS = ["Baishakh","Jestha","Ashadh","Shrawan","Bhadra","Ashwin","Kartik","Mangsir","Poush","Magh","Falgun","Chaitra"];

// Reference: AD 2000-01-01 == BS 2056-09-17
const REF_AD = Date.UTC(2000, 0, 1);
const REF_BS = { y: 2056, m: 9, d: 17 }; // m is 1-indexed

export function adToBs(date: Date): { y: number; m: number; d: number; monthName: string } | null {
  const utc = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  let days = Math.floor((utc - REF_AD) / 86400000);
  let { y, m, d } = REF_BS;
  while (days > 0) {
    const md = BS_CALENDAR[y]?.[m - 1];
    if (!md) return null;
    const left = md - d;
    if (days <= left) { d += days; days = 0; }
    else { days -= (left + 1); d = 1; m++; if (m > 12) { m = 1; y++; } }
  }
  return { y, m, d, monthName: BS_MONTHS[m - 1] };
}

export function fmtBsDate(d: string | Date | null | undefined): string {
  if (!d) return "—";
  const date = typeof d === "string" ? new Date(d) : d;
  const bs = adToBs(date);
  if (!bs) return "—";
  return `${bs.y}-${String(bs.m).padStart(2,"0")}-${String(bs.d).padStart(2,"0")} (${bs.monthName})`;
}
